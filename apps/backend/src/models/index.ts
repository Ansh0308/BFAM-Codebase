// ---- column helpers (mirror the style/shape used by the phase1 migration) ----
const id = (primaryKey = false, allowNull = false) => ({
  type: DataTypes.UUID,
  primaryKey,
  allowNull: primaryKey ? false : allowNull,
  ...(primaryKey ? { defaultValue: DataTypes.UUIDV4 } : {}),
});
const str = (length: number, allowNull = false) => ({ type: DataTypes.STRING(length), allowNull });
const text = (allowNull = false) => ({ type: DataTypes.TEXT, allowNull });
const dec = (precision: number, scale: number, allowNull = false, defaultValue?: number) => ({
  type: DataTypes.DECIMAL(precision, scale),
  allowNull,
  ...(defaultValue === undefined ? {} : { defaultValue }),
});
const date = (allowNull = false) => ({ type: DataTypes.DATE, allowNull });
const dateOnly = (allowNull = false) => ({ type: DataTypes.DATEONLY, allowNull });
const time = (allowNull = false) => ({ type: DataTypes.TIME, allowNull });
const smallint = (allowNull = false, defaultValue?: number) => ({
  type: DataTypes.SMALLINT,
  allowNull,
  ...(defaultValue === undefined ? {} : { defaultValue }),
});
const int = (allowNull = false, defaultValue?: number) => ({
  type: DataTypes.INTEGER,
  allowNull,
  ...(defaultValue === undefined ? {} : { defaultValue }),
});
const bool = (allowNull = false, defaultValue?: boolean) => ({
  type: DataTypes.BOOLEAN,
  allowNull,
  ...(defaultValue === undefined ? {} : { defaultValue }),
});
const json = (allowNull = false) => ({ type: DataTypes.JSON, allowNull });
const enumCol = (values: readonly string[], allowNull = false, defaultValue?: string) => ({
  type: DataTypes.ENUM(...values),
  allowNull,
  ...(defaultValue ? { defaultValue } : {}),
});
const char = (length: number, allowNull = false, defaultValue?: string) => ({
  type: DataTypes.CHAR(length),
  allowNull,
  ...(defaultValue ? { defaultValue } : {}),
});

