export function initModels(sequelize: Sequelize) {
  const models = Object.fromEntries(
    tableModelDefinitions.map((definition) => [
      definition.tableName,
      sequelize.define(definition.tableName, definition.attributes, {
        tableName: definition.tableName,
        underscored: true,
        timestamps: false,
      }),
    ]),
  );

  for (const association of associationDefinitions) {
    const source = models[association.from];
    const target = models[association.to];
    source.belongsTo(target, {
      foreignKey: association.fk,
      targetKey: association.targetKey,
      as: association.as,
    });
    if (association.hasManyAs) {
      target.hasMany(source, {
        foreignKey: association.fk,
        sourceKey: association.targetKey,
        as: association.hasManyAs,
      });
    }
  }

  return models;
}
